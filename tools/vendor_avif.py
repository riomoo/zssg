import os, shutil, json, re, glob
S='/tmp/avsrc'; B='/tmp/avb'; V=os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', 'vendor')
for d in ('libavif','aom','dav1d','libyuv'): shutil.rmtree(f'{V}/{d}', ignore_errors=True)
def cp(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True); shutil.copy2(src, dst)
ARCH={'x86','arm','arm64','mips','ppc','riscv','loongarch','neon','sve','avx2','sse4','x86_64','aarch64'}
def headers(root, dst, skipdirs=()):
    for dp, dns, fns in os.walk(root):
        rel=os.path.relpath(dp, root)
        parts=set(rel.split(os.sep))
        if parts & ARCH or parts & set(skipdirs) or '.git' in parts: continue
        for f in fns:
            if f.endswith(('.h','.inc')): cp(os.path.join(dp,f), os.path.join(dst, rel, f))
# ---- libavif
cp(f'{S}/libavif/LICENSE', f'{V}/libavif/LICENSE')
headers(f'{S}/libavif/include', f'{V}/libavif/include')
for f in ['alpha','avif','colr','colrconvert','diag','exif','gainmap','io','mem','obu','properties','rawdata','read','reformat','reformat_libsharpyuv','reformat_libyuv','sampletransform','scale','stream','utils','write','codec_aom','codec_dav1d']:
    cp(f'{S}/libavif/src/{f}.c', f'{V}/libavif/src/{f}.c')
# ---- aom
cp(f'{S}/aom/LICENSE', f'{V}/aom/LICENSE'); cp(f'{S}/aom/PATENTS', f'{V}/aom/PATENTS')
srcs=[l.strip() for l in open(f'{B}/aom_srcs.txt') if l.strip()]
for f in srcs:
    if f.startswith('config/') or f.startswith('gen_src/'): cp(f'{B}/aom/{f}', f'{V}/aom/{f}')
    else: cp(f'{S}/aom/{f}', f'{V}/aom/{f}')
headers(f'{S}/aom', f'{V}/aom', skipdirs=('test','tools','examples','apps','build','doc','stats','libyuv','googletest','libwebm','nasm','x86inc','googletest','gtest'))
for f in os.listdir(f'{B}/aom/config'):
    if f.endswith('.h'): cp(f'{B}/aom/config/{f}', f'{V}/aom/config/{f}')
open(f'{V}/aom/sources.txt','w').write('\n'.join(srcs)+'\n')
# ---- dav1d
cp(f'{S}/dav1d/COPYING', f'{V}/dav1d/COPYING')
headers(f'{S}/dav1d/include', f'{V}/dav1d/include')
headers(f'{S}/dav1d/src', f'{V}/dav1d/src')
d=json.load(open(f'{B}/dav1d/compile_commands.json'))
plain=set(); tmpl=set()
for x in d:
    if '/tools/' in x['file']: continue
    f=os.path.relpath(os.path.normpath(os.path.join(x['directory'],x['file'])), f'{S}/dav1d')
    (tmpl if '-DBITDEPTH=' in x['command'] else plain).add(f)
for f in plain|tmpl: cp(f'{S}/dav1d/{f}', f'{V}/dav1d/{f}')
cfg=open(f'{B}/dav1d/config.h').read()
# generic C build like Hugo's WebAssembly one: no architecture-specific code
cfg=re.sub(r'#define ARCH_(X86|X86_64|X86_32|AARCH64|ARM) 1', r'#define ARCH_\1 0', cfg)
os.makedirs(f'{V}/dav1d/config', exist_ok=True); open(f'{V}/dav1d/config/config.h','w').write(cfg)
cp(f'{B}/dav1d/include/vcs_version.h', f'{V}/dav1d/config/vcs_version.h')
open(f'{V}/dav1d/sources.txt','w').write('\n'.join(sorted(plain))+'\n')
open(f'{V}/dav1d/sources_tmpl.txt','w').write('\n'.join(sorted(tmpl))+'\n')
# ---- libyuv
cp(f'{S}/libyuv/LICENSE', f'{V}/libyuv/LICENSE')
headers(f'{S}/libyuv/include', f'{V}/libyuv/include')
ys=[os.path.basename(p) for p in glob.glob(f'{S}/libyuv/source/*.cc')]
for f in ys: cp(f'{S}/libyuv/source/{f}', f'{V}/libyuv/source/{f}')
open(f'{V}/libyuv/sources.txt','w').write('\n'.join(sorted(ys))+'\n')
print('ok')
# ---- sources.zig for build.zig
def arr(name, items):
    return f'pub const {name} = [_][]const u8{{\n' + ''.join(f'    "{i}",\n' for i in items) + '};\n'
yuv_common=['compare.cc','compare_common.cc','compare_gcc.cc','compare_win.cc','convert_argb.cc','convert.cc','convert_from_argb.cc','convert_from.cc','convert_jpeg.cc','convert_to_argb.cc','convert_to_i420.cc','cpu_id.cc','mjpeg_decoder.cc','mjpeg_validate.cc','planar_functions.cc','rotate_any.cc','rotate_argb.cc','rotate.cc','rotate_common.cc','rotate_gcc.cc','rotate_win.cc','row_any.cc','row_common.cc','row_gcc.cc','row_win.cc','scale_any.cc','scale_argb.cc','scale.cc','scale_common.cc','scale_gcc.cc','scale_rgb.cc','scale_uv.cc','scale_win.cc','video_common.cc']
avif_srcs=['alpha','avif','colr','colrconvert','diag','exif','gainmap','io','mem','obu','properties','rawdata','read','reformat','reformat_libsharpyuv','reformat_libyuv','sampletransform','scale','stream','utils','write','codec_aom','codec_dav1d']
out='// ZSSG — Zig Static Site Generator. Licensed under +THYME (see LICENSE).\n//! Generated by tools/vendor_avif.py: the C/C++ sources of the embedded AVIF codec.\n'
out+=arr('libavif',[f'src/{f}.c' for f in avif_srcs])
out+=arr('aom',srcs)
out+=arr('dav1d',sorted(plain))
out+=arr('dav1d_tmpl',sorted(tmpl))
out+=arr('libyuv',[f'source/{f}' for f in yuv_common])
open(os.path.join(os.path.dirname(V), 'avif_sources.zig'),'w').write(out)
print('sources.zig')
